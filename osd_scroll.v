//--------------------------------------------------------------------------
// 像素坐标 (与 de 同相)
//--------------------------------------------------------------------------
reg  de_d, vs_d;
wire de_rise = de & ~de_d;
wire de_fall = ~de & de_d;
wire vs_rise = vs & ~vs_d;
reg [9:0] px, py;

always @(posedge clk or posedge rst) begin
    if (rst) begin
        de_d <= 0; vs_d <= 0; px <= 0; py <= 0;
    end else begin
        de_d <= de; vs_d <= vs;
        if (vs_rise)      py <= 0;
        else if (de_fall) py <= (py==10'd479) ? 10'd0 : py + 10'd1;
        if (de_rise)      px <= 0;
        else if (de)      px <= px + 10'd1;
    end
end

//--------------------------------------------------------------------------
// 连续流跑马灯: 句子按周期 LOOP_W = 文本宽312 + 句间距64 平铺。
//   周期 < 屏宽 → 屏幕同时可见 1~2 份, 前句未走完后句已跟上, 间距恒定(节奏平稳)。
//--------------------------------------------------------------------------
localparam [8:0] LOOP_W = 9'd376;                      // 312 + 64

reg [8:0] scroll;                                      // 0..375
always @(posedge clk or posedge rst) begin
    if (rst)          scroll <= 9'd0;
    else if (vs_rise) scroll <= (scroll >= LOOP_W - 9'd1) ? 9'd0 : scroll + SCROLL_STEP;
end

wire [9:0] scol = {1'b0, px} + {1'b0, scroll};         // 0..1014
wire [9:0] md1  = (scol >= {1'b0, LOOP_W}) ? (scol - {1'b0, LOOP_W}) : scol;
wire [9:0] col  = (md1  >= {1'b0, LOOP_W}) ? (md1  - {1'b0, LOOP_W}) : md1;   // 0..375

//--------------------------------------------------------------------------
// 电影式底部渐变: 逐像素 out = rgb - rgb*alpha/256 (a=0 时完全无损)
// 注意: Verilog 中 8bit*8bit 结果位宽=8bit, 必须先接 16bit 中间量再取高位!
//--------------------------------------------------------------------------
wire [9:0] grad_dy  = py - GRAD_START;
// 注意位宽: grad_dy<=99, 须用 8bit 承接再左移(7bit 左移会截断)
wire [7:0] gd8    = grad_dy[7:0];
wire [7:0] grad_a = (py < GRAD_START) ? 8'd0
                  : (gd8 << 1) + (gd8 >> 2);     // py=479 → 198+24=222 (87%暗)
wire [15:0] mulr = rgb_in[23:16] * grad_a;
wire [15:0] mulg = rgb_in[15:8]  * grad_a;
wire [15:0] mulb = rgb_in[7:0]   * grad_a;
wire [7:0] gr = rgb_in[23:16] - mulr[15:8];
wire [7:0] gg = rgb_in[15:8]  - mulg[15:8];
wire [7:0] gb = rgb_in[7:0]   - mulb[15:8];
wire [23:0] grad_rgb = {gr, gg, gb};

//--------------------------------------------------------------------------
// 中文行: 16x16 纯白字(无描边, 避免 16px 小字被描边吃笔画)
//--------------------------------------------------------------------------
wire in_cn  = en_v && (py >= BAR_Y_CN) && (py < BAR_Y_CN + 12'd16);
wire [3:0] row_cn = py[3:0] - BAR_Y_CN[3:0];            // (py-BAR_Y_CN) mod 16
// 中文行水平居中于英文行: 右移 (312-208)/2 = 52
wire txt_cn = (col >= 10'd52) && (col < 10'd260);      // 52 + 208
wire [8:0] col_cn = col[8:0] - 9'd52;                  // 0..207
wire [3:0] ci = col_cn[7:4];
wire [3:0] cc = col_cn[3:0];
wire [15:0] cn_c = rom_cn[{ci, row_cn}];
wire cn_core = txt_cn && cn_c[4'd15 - cc];

//--------------------------------------------------------------------------
// 英文行: 8x16 纯白字
//--------------------------------------------------------------------------
wire in_en  = en_v && (py >= BAR_Y_EN) && (py < BAR_Y_EN + 12'd16);
wire [3:0] row_en = py[3:0] - BAR_Y_EN[3:0];
wire txt_en = (col < 10'd312);                       // 39 x 8
wire [5:0] ei = col[8:3];
wire [2:0] ec = col[2:0];
wire [7:0] en_c = rom_en[{ei, row_en}];
wire en_core = txt_en && en_c[3'd7 - ec];

//--------------------------------------------------------------------------
// 输出: 描边黑 > 字白 > 渐变图像
//--------------------------------------------------------------------------
assign rgb_out = (!en_v)              ? 24'd0 :
                 (in_cn && cn_core)   ? 24'hFFFFFF :
                 (in_en && en_core)   ? 24'hFFFFFF :
                                        grad_rgb;

endmodule
